<?php
namespace Emmakex\PrestaShopSalesforceMarketingCloud\Growth;

use PDO;
use RuntimeException;

/**
 * G7 durable claim/lease/cancellation on the SAME G3 Growth outbox table.
 *
 * DORMANT sandbox-certified component, not wired into installed module.
 * Uses no second queue, no payload storage, no HTTP and no marketing sends.
 * An explicit sandbox credential/env guard keeps it away from merchant DBs.
 *
 * A 202 upsert receipt never marks delivery complete. Expired leases and
 * interrupted attempts remain uncertain until a separate reconciliation.
 * Merely claiming a row never authorizes the actual remote operation.
 */
final class GrowthOutboxDeliveryLease
{
    private $db;

    public function __construct(PDO $db)
    {
        if (getenv('G3_CI_ENABLE') !== 'yes_sandbox_only'
            || getenv('G7_CI_LEASE_ENABLE') !== 'yes_synthetic_only'
            || getenv('G3_CI_DSN')
                !== 'mysql:host=127.0.0.1;port=3306;dbname=g3_ci;charset=utf8mb4'
            || getenv('G3_CI_USER') !== 'g3_ci_user'
            || getenv('G3_CI_PASSWORD') !== 'g3_ci_pass_only'
            || $db->query('SELECT DATABASE()')->fetchColumn() !== 'g3_ci'
            || strpos((string)$db->query('SELECT CURRENT_USER()')
                ->fetchColumn(), 'g3_ci_user@') !== 0) {
            throw new RuntimeException('g7_lease_sandbox_only');
        }
        $db->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);
        $db->setAttribute(PDO::ATTR_EMULATE_PREPARES, false);
        $this->db = $db;
    }

    /**
     * Atomically claim the current revision under the G3 entity ledger.
     *
     * An expected version that is stale, cancelled, not ready or claimed
     * elsewhere returns false. The lease token is generated by the caller
     * and never included in diagnostics. Claims are NOT export permits.
     */
    public function claim($namespace, $shop, $type, $id, $sequence, $token, $ttl)
    {
        self::scope($namespace,$shop,$type,$id,$sequence);
        self::token($token);
        if (!is_int($ttl) || $ttl < 30 || $ttl > 900) {
            throw new RuntimeException('g7_lease_ttl_invalid');
        }
        $q=$this->db->prepare(
            "UPDATE g3_growth_outbox_v1 o "
            . "INNER JOIN g3_growth_entity_ledger_v1 l "
            . "ON l.source_namespace=o.source_namespace AND l.shop_id=o.shop_id "
            . "AND l.entity_type=o.entity_type AND l.entity_id=o.entity_id "
            . "SET o.delivery_state='claimed',o.lease_token_hash=?,"
            . "o.lease_until_epoch=UNIX_TIMESTAMP()+?,"
            . "o.delivery_attempts=o.delivery_attempts+1 "
            . "WHERE o.accepted_sequence=? AND o.source_namespace=? "
            . "AND o.shop_id=? AND o.entity_type=? AND o.entity_id=? "
            . "AND o.status='blocked' AND l.status='blocked' "
            . "AND l.latest_accepted_sequence=o.accepted_sequence "
            . "AND o.delivery_state='ready' AND o.delivery_attempts<3"
        );
        $q->execute([
            hash('sha256',$token),$ttl,$sequence,$namespace,$shop,$type,$id
        ]);
        if ($q->rowCount()>1) {
            throw new RuntimeException('g7_lease_multi_claim_rejected');
        }
        return $q->rowCount()===1;
    }

    /**
     * A local negative event is durably recorded. If the row was already
     * claimed, remote side effects may be in flight; do not assert they
     * were prevented by this database update.
     */
    public function cancel($namespace, $shop, $type, $id, $sequence)
    {
        self::scope($namespace,$shop,$type,$id,$sequence);
        $q=$this->db->prepare(
            "UPDATE g3_growth_outbox_v1 "
            . "SET delivery_state='cancelled',lease_token_hash=NULL,"
            . "lease_until_epoch=NULL "
            . "WHERE accepted_sequence=? AND source_namespace=? "
            . "AND shop_id=? AND entity_type=? AND entity_id=? "
            . "AND delivery_state IN ('blocked','ready','claimed','reconcile','held')"
        );
        $q->execute([$sequence,$namespace,$shop,$type,$id]);
        return $q->rowCount()===1;
    }

    /**
     * Called only after a future approved transport obtains HTTP 202.
     * The state is awaiting remote verification, NOT delivered.
     */
    public function markAcceptedUnconfirmed(
        $namespace,$shop,$type,$id,$sequence,$token
    ) {
        return $this->endLease(
            $namespace,$shop,$type,$id,$sequence,$token,'reconcile',202
        );
    }

    /**
     * A timeout / lost HTTP response has an UNKNOWN remote outcome even
     * before the lease expires. Quarantine immediately, never claim that
     * the remote request failed and never put the row back into ready.
     * Token and unexpired ownership are required; a cancelled claim cannot
     * be revived by a late response. No HTTP status is fabricated.
     */
    public function markUnknownUnconfirmed(
        $namespace,$shop,$type,$id,$sequence,$token
    ) {
        return $this->endLease(
            $namespace,$shop,$type,$id,$sequence,$token,'reconcile',null
        );
    }

    /** An explicit local hold after a known failure, never auto-retry. */
    public function holdClaim(
        $namespace,$shop,$type,$id,$sequence,$token,$httpStatus
    ) {
        if (!is_int($httpStatus) || $httpStatus < 100 || $httpStatus > 599
            || $httpStatus===202) {
            throw new RuntimeException('g7_lease_hold_http_invalid');
        }
        return $this->endLease(
            $namespace,$shop,$type,$id,$sequence,$token,'held',$httpStatus
        );
    }

    /**
     * An expired lease has an UNKNOWN remote outcome.
     * Quarantine it for reconciliation and never return it to READY.
     */
    public function quarantineExpired($namespace, $shop, $type, $id, $sequence)
    {
        self::scope($namespace,$shop,$type,$id,$sequence);
        $q=$this->db->prepare(
            "UPDATE g3_growth_outbox_v1 "
            . "SET delivery_state='reconcile',lease_token_hash=NULL,"
            . "lease_until_epoch=NULL "
            . "WHERE accepted_sequence=? AND source_namespace=? "
            . "AND shop_id=? AND entity_type=? AND entity_id=? "
            . "AND delivery_state='claimed' "
            . "AND lease_until_epoch<=UNIX_TIMESTAMP()"
        );
        $q->execute([$sequence,$namespace,$shop,$type,$id]);
        return $q->rowCount()===1;
    }

    /** Minimal status: never returns source keys, email, lease token or PII. */
    public function inspect($namespace, $shop, $type, $id, $sequence)
    {
        self::scope($namespace,$shop,$type,$id,$sequence);
        $q=$this->db->prepare(
            'SELECT delivery_state,delivery_attempts,lease_until_epoch,'
            . 'delivery_last_http FROM g3_growth_outbox_v1 '
            . 'WHERE accepted_sequence=? AND source_namespace=? '
            . 'AND shop_id=? AND entity_type=? AND entity_id=?'
        );
        $q->execute([$sequence,$namespace,$shop,$type,$id]);
        $row=$q->fetch(PDO::FETCH_ASSOC);
        if (!is_array($row)) {
            return ['status'=>'not_found','delivery_authorized'=>false];
        }
        return [
            'status'=>'sandbox_only',
            'state'=>(string)$row['delivery_state'],
            'attempts'=>(int)$row['delivery_attempts'],
            'lease_active'=>($row['lease_until_epoch']!==null
                && (int)$row['lease_until_epoch']>time()),
            'last_http'=>( $row['delivery_last_http']===null
                ? null : (int)$row['delivery_last_http']),
            'record_delivered_certified'=>false,
            'delivery_authorized'=>false,
            'marketing_sends_authorized'=>false,
        ];
    }

    private function endLease(
        $namespace,$shop,$type,$id,$sequence,$token,$state,$http
    ) {
        self::scope($namespace,$shop,$type,$id,$sequence);
        self::token($token);
        $q=$this->db->prepare(
            'UPDATE g3_growth_outbox_v1 SET delivery_state=?,'
            . 'delivery_last_http=?,lease_token_hash=NULL,lease_until_epoch=NULL '
            . 'WHERE accepted_sequence=? AND source_namespace=? '
            . 'AND shop_id=? AND entity_type=? AND entity_id=? '
            . "AND delivery_state='claimed' AND lease_token_hash=? "
            . 'AND lease_until_epoch>UNIX_TIMESTAMP()'
        );
        $q->execute([
            $state,$http,$sequence,$namespace,$shop,$type,$id,
            hash('sha256',$token)
        ]);
        return $q->rowCount()===1;
    }

    private static function token($value)
    {
        if (!is_string($value)
            || !preg_match('/^[a-f0-9]{64}$/D',$value)) {
            throw new RuntimeException('g7_lease_token_invalid');
        }
    }

    private static function scope($namespace,$shop,$type,$id,$sequence)
    {
        if (!is_string($namespace)
            || !preg_match('/^[a-z][a-z0-9_]{5,31}$/D',$namespace)
            || !is_int($shop) || $shop<1
            || !in_array($type,['customer','order'],true)
            || !is_int($id) || $id<1 || !is_int($sequence)
            || $sequence<1) {
            throw new RuntimeException('g7_lease_scope_invalid');
        }
    }
}
